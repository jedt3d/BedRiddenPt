// Generates lib/theme/tokens.dart from design/tokens.json (the Figma
// variables export). Dart SDK only, no packages.
//
// Run from the project root:   dart run tool/gen_tokens.dart
//
// When the Figma tokens change: re-export design/tokens.json, review its
// diff, run this script and commit both files. CI fails if tokens.dart is
// not what this script produces.

import 'dart:convert';
import 'dart:io';

const inputPath = 'design/tokens.json';
const outputPath = 'lib/theme/tokens.dart';

void main() {
  final json = jsonDecode(File(inputPath).readAsStringSync()) as Map<String, dynamic>;
  final out = StringBuffer()
    ..writeln('// GENERATED by tool/gen_tokens.dart from $inputPath. Do not edit.')
    ..writeln('// ${json['source']}')
    ..writeln('// Font: ${json['fontFamily']}.')
    ..writeln('// The TextStyles set no fontFamily, so they inherit the platform')
    ..writeln('// system font from CupertinoApp.')
    ..writeln()
    ..writeln("import 'package:flutter/widgets.dart';")
    ..writeln();

  // Colours: the semantic set, named by its "flutter" field.
  out
    ..writeln('/// Semantic colours (Figma "color" collection).')
    ..writeln('abstract final class AppColors {');
  final colors = json['color'] as Map<String, dynamic>;
  for (final MapEntry(key: token, value: v as Map<String, dynamic>) in colors.entries) {
    final name = (v['flutter'] as String).replaceFirst('AppColors.', '');
    final hex = (v['value'] as String).substring(1).toUpperCase();
    out
      ..writeln('  /// `$token` = `${v['alias']}` ${v['value']}.')
      ..writeln('  static const Color $name = Color(0xFF$hex);');
    final opacity = v['opacityInUse'];
    if (opacity != null) {
      for (final (suffix, value) in _opacities(opacity)) {
        out
          ..writeln('  /// Opacity used with [$name] ($token, "$opacity").')
          ..writeln('  static const double ${name}Opacity$suffix = $value;');
      }
    }
  }
  out
    ..writeln('}')
    ..writeln();

  _numbers(out, 'AppSpace', 'Spacing in logical pixels (Figma "space").',
      json['space'] as Map<String, dynamic>);
  _numbers(out, 'AppRadius', 'Corner radii in logical pixels (Figma "radius").',
      json['radius'] as Map<String, dynamic>);

  // Text styles: [size, weight] or [size, weight, lineHeight].
  out
    ..writeln('/// Text styles (Figma "text"). No colour: set it from [AppColors].')
    ..writeln('abstract final class AppText {');
  final text = json['text'] as Map<String, dynamic>;
  for (final MapEntry(key: name, value: v as List) in text.entries) {
    final size = v[0] as num;
    final weight = _weights[v[1]] ?? (throw FormatException('Unknown weight ${v[1]} in $name'));
    final height = v.length > 2 ? ', height: ${v[2]} / $size' : '';
    out
      ..writeln('  /// ${v[1]} $size${v.length > 2 ? '/${v[2]}' : ''}.')
      ..writeln('  static const TextStyle $name = '
          'TextStyle(fontSize: $size, fontWeight: FontWeight.$weight$height);');
  }
  out.writeln('}');

  File(outputPath)
    ..createSync(recursive: true)
    ..writeAsStringSync(out.toString());
  // Format so the output is stable and readable; CI diffs it against git.
  final format = Process.runSync(Platform.resolvedExecutable, ['format', outputPath]);
  if (format.exitCode != 0) {
    stderr.write(format.stderr);
    exit(format.exitCode);
  }
  stdout.writeln('Wrote $outputPath');
}

const _weights = {'Regular': 'w400', 'Medium': 'w500', 'SemiBold': 'w600', 'Bold': 'w700'};

/// `0.94` → [('', 0.94)]; `"0.97 alert, 0.95 sheet"` → [('Alert', 0.97), ('Sheet', 0.95)].
List<(String, num)> _opacities(Object opacity) {
  if (opacity is num) return [('', opacity)];
  return [
    for (final part in (opacity as String).split(','))
      if (part.trim().split(RegExp(r'\s+')) case [final value, ...final words])
        (words.map((w) => w[0].toUpperCase() + w.substring(1)).join(), num.parse(value)),
  ];
}

void _numbers(StringBuffer out, String cls, String doc, Map<String, dynamic> values) {
  out
    ..writeln('/// $doc')
    ..writeln('abstract final class $cls {');
  for (final MapEntry(:key, :value) in values.entries) {
    out.writeln('  static const double $key = ${(value as num).toDouble()};');
  }
  out
    ..writeln('}')
    ..writeln();
}
